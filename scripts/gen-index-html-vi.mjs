#!/usr/bin/env node
// Regenerates the AIXML of source/Server/RemoteVI Index HTML.vi from web/index.html.
//
// The toolkit embeds the browser client as ONE string constant, so a built EXE needs no
// support files. Whenever web/index.html changes, refresh that constant:
//
//   1. node scripts/gen-index-html-vi.mjs
//        writes tools/aixml/Server/index_html.xml (the whole file as the constant's value)
//   2. compose the VI from it, with LabVIEW 2025 running, either
//        - with labview-mcp:  lvai_generate_vi  aiXmlFilePath=tools\aixml\Server\index_html.xml
//                             viPath=source\Server\RemoteVI Index HTML.vi
//        - or directly:       node scripts/gen-index-html-vi.mjs --compose
//          (runs tools/aixml/compose.py with labview-mcp's bundled Python; close the VI in
//           LabVIEW first, LabVIEW does not reload a VI that is changed on disk)
//   3. check it: run the VI and compare `html` with the file (length 12778 and SHA-256 at the
//      time of writing); `node scripts/gen-index-html-vi.mjs --print-hash` prints both.
//
// Escaping (docs: labview-mcp lvai_aixml_reference section 6): AIXML decodes \XX hex escapes
// inside a value, so backslash, comma and every byte outside printable ASCII are written as
// \XX, and XML's own five characters as entities. The file must be ASCII; a non-ASCII byte
// is refused so the constant can never differ from the file.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const htmlPath = path.join(root, 'web', 'index.html');
const outPath = path.join(root, 'tools', 'aixml', 'Server', 'index_html.xml');
const viPath = path.join(root, 'source', 'Server', 'RemoteVI Index HTML.vi');

const bytes = fs.readFileSync(htmlPath);
const hash = crypto.createHash('sha256').update(bytes).digest('hex');
if (process.argv.includes('--print-hash')) {
  console.log(`${bytes.length} bytes, sha256 ${hash}`);
  process.exit(0);
}

const hex = (b) => '\\' + b.toString(16).toUpperCase().padStart(2, '0');
let value = '';
for (const b of bytes) {
  if (b > 126) throw new Error(`web/index.html is not ASCII (byte 0x${b.toString(16)})`);
  if (b < 32 || b === 0x5c || b === 0x2c) value += hex(b);
  else if (b === 0x26) value += '&amp;';
  else if (b === 0x3c) value += '&lt;';
  else if (b === 0x3e) value += '&gt;';
  else if (b === 0x22) value += '&quot;';
  else if (b === 0x27) value += '&apos;';
  else value += String.fromCharCode(b);
}

const xml = `<VI _name="RemoteVI Index HTML.vi" description="Returns the browser client\\2C web\\5Cindex.html\\2C as one string constant (${bytes.length} bytes\\2C SHA-256 ${hash}). Generated by scripts\\5Cgen-index-html-vi.mjs - do not edit the constant by hand\\3B regenerate it when the client changes. error in passes through unchanged.">
  <FreeLabel comment="Generated from web/index.html" uid="lbl" uid_parent="root"/>
  <Control _name="error in" conIdx="11" connection="recommended" description="Standard error in\\2C passed through." outputs="value:ei.value" type="cluster{bool.status,int32.code,string.source}" uid="ei" uid_parent="root" value="[false,0,]"/>
  <Constant outputs="value:page.value" type="string" uid="page" uid_parent="root" value="${value}"/>
  <Indicator _name="html" conIdx="4" connection="recommended" description="The exact bytes of web\\5Cindex.html." inputs="value:page.value" type="string" uid="o_html" uid_parent="root" value=""/>
  <Indicator _name="error out" conIdx="15" connection="recommended" description="Standard error out." inputs="value:ei.value" type="cluster{bool.status,int32.code,string.source}" uid="eo" uid_parent="root" value="[false,0,]"/>
</VI>
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, xml, 'ascii');
console.log(`wrote ${path.relative(root, outPath)} from ${bytes.length} bytes (sha256 ${hash})`);

if (process.argv.includes('--compose')) {
  const bin = process.env.LVMCP_BIN
    ?? path.join(process.env.USERPROFILE, '.claude', 'plugins', 'cache', 'zuehlke-labview', 'labview-mcp', '2.2.0', 'bin');
  const r = spawnSync(path.join(bin, 'pylabview', 'python.exe'),
    [path.join(root, 'tools', 'aixml', 'compose.py'), outPath, viPath], { stdio: 'inherit' });
  process.exit(r.status ?? 1);
}
