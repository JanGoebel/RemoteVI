BANNER = (0, 102, 153)
WHITE = (255, 255, 255)
GREY = (221, 221, 221)
ROWS = (2, 12, 21)  # top row of the banner text and of the two lines


def render(line1, line2='', line3='', bg=WHITE, banner=BANNER):
    im = Image.new('RGB', (32, 32), bg)
    px = im.load()
    for x in range(32):
        px[x, 0] = px[x, 31] = (0, 0, 0)
        px[0, x] = px[31, x] = (0, 0, 0)
    for y in range(1, 10):
        for x in range(1, 31):
            px[x, y] = banner
    for text, y0, ink in ((line1, ROWS[0], bg), (line2, ROWS[1], (0, 0, 0)), (line3, ROWS[2], (0, 0, 0))):
        text = text.upper()
        if len(text) > 5:
            raise ValueError('more than 5 characters: %r' % text)
        x0 = (32 - 6 * len(text)) // 2
        for i, ch in enumerate(text):
            if ch == ' ':
                continue
            for y, row in enumerate(GLYPHS[ch]):
                for x, bit in enumerate(row):
                    if bit == '1':
                        px[x0 + 6 * i + x, y0 + y] = ink
    return im
